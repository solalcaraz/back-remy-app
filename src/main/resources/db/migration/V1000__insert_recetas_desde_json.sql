-- Falla explicitamente si algun ingrediente del JSON no existe en la tabla ingredientes.
DO $$
DECLARE
    faltantes TEXT;
BEGIN
    SELECT STRING_AGG(DISTINCT sri.nombre_ingrediente, ', ' ORDER BY sri.nombre_ingrediente)
    INTO faltantes
    FROM seed_receta_ingredientes sri
    LEFT JOIN ingredientes i ON i.nombre = sri.nombre_ingrediente
    WHERE i.id IS NULL;

    IF faltantes IS NOT NULL THEN
        RAISE EXCEPTION 'Ingredientes inexistentes referenciados por recetas: %', faltantes;
    END IF;
END $$;

-- Si ya existian recetas seed con el mismo nombre en una DB de prueba, se reemplazan para evitar duplicados.
DELETE FROM recetas r
USING seed_recetas sr
WHERE r.nombre = sr.nombre;

INSERT INTO recetas (nombre, tiempo_en_minutos, porciones, dificultad, descripcion, img_url)
SELECT nombre, tiempo_en_minutos, porciones, dificultad, descripcion, img_url
FROM seed_recetas
ORDER BY seed_id;

INSERT INTO receta_ingredientes (receta_id, ingrediente_id, cantidad, unidad_medida, tipo_ingrediente)
SELECT
    r.id,
    i.id,
    sri.cantidad,
    sri.unidad_medida,
    sri.tipo_ingrediente
FROM seed_receta_ingredientes sri
JOIN seed_recetas sr ON sr.seed_id = sri.seed_receta_id
JOIN recetas r ON r.nombre = sr.nombre
JOIN ingredientes i ON i.nombre = sri.nombre_ingrediente
ORDER BY sr.seed_id;

INSERT INTO pasos (receta_id, orden, titulo, descripcion, detalle, tiempo_estimado_minutos, tip, imagen_url)
SELECT
    r.id,
    sp.orden,
    sp.titulo,
    sp.descripcion,
    sp.detalle,
    sp.tiempo_estimado_minutos,
    sp.tip,
    sp.imagen_url
FROM seed_pasos sp
JOIN seed_recetas sr ON sr.seed_id = sp.seed_receta_id
JOIN recetas r ON r.nombre = sr.nombre
ORDER BY sr.seed_id, sp.orden;

INSERT INTO receta_tags (receta_id, tags)
SELECT r.id, srt.tag
FROM seed_receta_tags srt
JOIN seed_recetas sr ON sr.seed_id = srt.seed_receta_id
JOIN recetas r ON r.nombre = sr.nombre
ON CONFLICT (receta_id, tags) DO NOTHING;

-- Recalcula costo y perfil economico de las recetas insertadas.
WITH CostosReceta AS (
    SELECT
        ri.receta_id,
        COALESCE(SUM(
            CASE
                WHEN i.categoria IN ('LACTEOS', 'ACEITES_GRASAS', 'ESPECIAS_CONDIMENTOS', 'OTROS_ESENCIALES')
                    THEN COALESCE(pi.precio, 0) / 100.0
                ELSE COALESCE(pi.precio, 0)
            END
        ), 0) AS costo_total
    FROM receta_ingredientes ri
    JOIN ingredientes i ON ri.ingrediente_id = i.id
    LEFT JOIN precios_ingredientes pi ON ri.ingrediente_id = pi.ingrediente_id
    JOIN recetas r ON r.id = ri.receta_id
    JOIN seed_recetas sr ON sr.nombre = r.nombre
    GROUP BY ri.receta_id
)
UPDATE recetas r
SET
    costo_total_compra = c.costo_total,
    perfil_economico = CASE
        WHEN c.costo_total < 6000 THEN 'BAJO_PRESUPUESTO'
        WHEN c.costo_total < 15000 THEN 'INTERMEDIO'
        ELSE 'FLEXIBLE'
    END
FROM CostosReceta c
WHERE r.id = c.receta_id;
